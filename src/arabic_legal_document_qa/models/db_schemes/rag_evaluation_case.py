from pydantic import BaseModel, Field


class RAGEvaluationCase(BaseModel):
    case_id: str = Field(description="Unique stable ID for the test case")
    user_input: str = Field(min_length=3, description="Input query or legal question")
    retrieved_contexts: list[str] = Field(
        min_length=1, description="Context chunks retrieved by the RAG system"
    )
    response: str = Field(
        min_length=1, description="Answer generated by the RAG system"
    )
    reference: str = Field(min_length=1, description="Ground truth answer or citation")
    slice: str = Field(description="Category for grouping test cases")
    source_revision: str = Field(
        default="egyptian_civil_code_v1.0", description="Document/data version snapshot"
    )

    def to_ragas_sample(self):
        from ragas import SingleTurnSample

        return SingleTurnSample(
            user_input=self.user_input,
            retrieved_contexts=self.retrieved_contexts,
            response=self.response,
            reference=self.reference,
        )
